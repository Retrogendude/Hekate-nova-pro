"""Build a self-contained Win64 SD installer using the verified Nova ZIP bundles."""
from pathlib import Path
from zipfile import ZipFile
import hashlib,json,subprocess,os
from PIL import Image,ImageDraw
W=Path(__file__).resolve().parents[2];D=W/'work/nova-installer-1.2';O=W/'outputs';B=D/'build';B.mkdir(exist_ok=True)
T=W/'work/toolchains/w64devkit/bin';sha=lambda b:hashlib.sha256(b).hexdigest()
report=json.loads((W/'work/nova34a5-package-check.json').read_text())
lines=['/* Exact verified package inventory; generated by build_installer.py. */']
for variant,suffix in ((4,''),(8,'-8GB')):
 archive=O/('hekate-nova-pro-v34-alpha5'+suffix+'.zip');assert sha(archive.read_bytes())==report['archives'][archive.name]['sha256']
 dest=B/f'payload{variant}';dest.mkdir(exist_ok=True);items=[]
 with ZipFile(archive)as z:
  for n in z.namelist():
   if n.endswith('/'):continue
   assert n.isascii()and not n.startswith('/')and '..'not in n.split('/')and ':'not in n
   assert n.lower()not in ('package.cab','bootloader/nyx.ini','bootloader/hekate_ipl.ini')
   data=z.read(n);p=dest/n;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data);items.append((n,len(data),sha(data)))
 main=next((name,size,h)for name,size,h in items if name.startswith('hekate_nova_pro_')and name.endswith('.bin'))
 alias='bootloader/payloads/'+main[0];data=(dest/main[0]).read_bytes();assert sha(data)==main[2]
 target=dest/alias;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data);
 if alias not in {n for n,_,_ in items}:items.append((alias,len(data),main[2]))
 lines.append(f'#define COUNT{variant} {len(items)}\nstatic const PackageFile files{variant}[]={{')
 for n,size,h in items:lines.append('{L'+json.dumps(n)+','+str(size)+'u,"'+h+'"},')
 lines.append('};')
 cab=B/f'payload{variant}.cab';ddf=B/f'payload{variant}.ddf'
 commands=['.OPTION EXPLICIT','.Set Cabinet=on','.Set Compress=on','.Set CompressionType=LZX','.Set CompressionMemory=21','.Set MaxDiskSize=0',f'.Set CabinetNameTemplate=payload{variant}.cab',f'.Set DiskDirectoryTemplate="{B}"',f'.Set InfFileName="{B}/payload{variant}.inf"',f'.Set RptFileName="{B}/payload{variant}.rpt"']
 for n,_,_ in items:commands.append('"'+str(dest/n)+'" "'+n.replace('/','\\')+'"')
 ddf.write_text('\n'.join(commands),encoding='ascii')
 r=subprocess.run(['C:/Windows/System32/makecab.exe','/F',str(ddf)],cwd=B,capture_output=True,text=True)
 if r.returncode:print(r.stdout+r.stderr);raise SystemExit(r.returncode)
 assert cab.is_file();lines.append(f'static const char cab{variant}hash[]="{sha(cab.read_bytes())}";');print(f'Cabinet {variant}: {cab.stat().st_size} bytes, {len(items)} files',flush=True)
(D/'payload.h').write_text('\n'.join(lines),encoding='utf-8')
# App icon follows the existing Nova hexagon/N mark, drawn as vector paths.
im=Image.new('RGBA',(1024,1024),(0,0,0,0));draw=ImageDraw.Draw(im)
