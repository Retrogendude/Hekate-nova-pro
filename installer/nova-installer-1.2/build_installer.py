subprocess.run([str(T/'windres.exe'),'--codepage=65001',str(D/'installer.rc'),'-O','coff','-o',str(B/'resources.o')],cwd=D,check=True)
common=[str(T/'gcc.exe'),'-std=gnu11','-O2','-Wall','-Wextra','-finput-charset=UTF-8','-static','-municode','-I'+str(D),str(D/'install.c')]
libs=['-lsetupapi','-ladvapi32','-lcomctl32','-lgdi32','-luser32','-lshell32']
